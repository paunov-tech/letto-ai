const js = `/* public/js/destination-matrix.js — GENERATED by scripts/generate-destination-matrix.mjs
 * PSEO_ENABLED=${PSEO_ON ? 1 : 0} · DO NOT EDIT BY HAND · re-run the generator on the rollout flip.
 *
 * Origin→destination matrix on the homepage. Link target is baked server-side
 * (PSEO_ENABLED): ${PSEO_ON ? '/letovi-iz-{origin}-za-{dest} (pSEO)' : '/letovi-{dest} (existing static landings)'}.
 * Selected origin persists in localStorage ('letto_pseo_origin', default BEG).
 */
(function () {
  'use strict';
  var MOUNT = document.getElementById('destination-matrix');
  if (!MOUNT) return;

  var STORE_KEY = 'letto_pseo_origin', DEFAULT_ORIGIN = 'BEG';
  var ORIGINS = ${JSON.stringify(ORIGINS)};
  var DESTS = ${JSON.stringify(DESTS)};

  // Baked server-side from PSEO_ENABLED — no runtime flag check.
  function hrefFor(o, d) { return ${hrefExpr}; }

  function getOrigin() {
    var code; try { code = localStorage.getItem(STORE_KEY); } catch (e) {}
    return ORIGINS.some(function (o) { return o.code === code; }) ? code : DEFAULT_ORIGIN;
  }
  function setOrigin(code) { try { localStorage.setItem(STORE_KEY, code); } catch (e) {} }
  function originBy(code) { for (var i = 0; i < ORIGINS.length; i++) if (ORIGINS[i].code === code) return ORIGINS[i]; return ORIGINS[0]; }

  function injectStyle() {
    if (document.getElementById('dm-css')) return;
    var s = document.createElement('style');
    s.id = 'dm-css';
    s.textContent = ${JSON.stringify(CSS)};
    document.head.appendChild(s);
  }

  function render() {
    var current = getOrigin(), o = originBy(current);
    var chips = ORIGINS.map(function (x) {
      return '<button class="dm-chip" data-code="' + x.code + '" aria-pressed="' + (x.code === current) + '">' + x.name + '</button>';
    }).join('');
    var opts = ORIGINS.map(function (x) {
      return '<option value="' + x.code + '"' + (x.code === current ? ' selected' : '') + '>' + x.name + '</option>';
    }).join('');
    var grid = DESTS.map(function (d) {
      return '<a class="dm-link" href="' + hrefFor(o, d) + '"><span class="dm-city">' + d.city + '</span><small>iz ' + o.name + '</small></a>';
    }).join('');
    MOUNT.innerHTML =
      '<div class="dm-origins" role="group" aria-label="Polazni grad">' + chips + '</div>' +
      '<select class="dm-select" aria-label="Polazni grad">' + opts + '</select>' +
      '<div class="dm-grid">' + grid + '</div>';
    MOUNT.querySelectorAll('.dm-chip').forEach(function (btn) {
      btn.addEventListener('click', function () { setOrigin(btn.getAttribute('data-code')); render(); });
    });
    var sel = MOUNT.querySelector('.dm-select');
    if (sel) sel.addEventListener('change', function () { setOrigin(sel.value); render(); });
  }

  injectStyle();
  render();
})();
`;

